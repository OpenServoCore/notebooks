"""The servo rig for the stage 3 camera experiments: a base that holds one
MG90, one osc-dev-v006 board and a reference tag in one rigid piece, three
mounts that take turns on the servo's four-arm horn, the camera mount that
carries the horn's tag, the stall mount that bolts the horn to the base and
the load mount with a coin block screwed to it, and a two-piece cap that
carries a tag paper flat and pushes onto the camera mount, the load mount
or the pad.

A phone films the rig from straight above, and the camera reads the horn's
angle from the tag on the camera mount against the tag on the base. That reading is
the independent reference for the potentiometer, so nothing may move between
clips and no wire may cross a tag. The tags are 25 mm ArUco squares with a
6.25 mm white border, filmed from 250 mm; the size and the distance come from
the camera-tag notebook of stage 0.

The servo sinks into the base and sits on its mounting ears on a ledge, with
the body snug in a pocket that runs through to the underside, so the servo
pushes out from below. The ledge is cut half a millimeter low and card shims
under the ears set the horn's height, so the top face of the horn's arm
plate stands 1.5 mm above the base top, inside a 1 to 2 mm band, turning in
a shallow well. The
servo lead drops through a slot in the pocket's back wall and runs to the
back in a channel under the base. The base top carries the reference tag's
pad, the board's pocket with its pads and pilots, the stall screw's hole
and two grooves at the back for the bus and power leads. Each of the three
leads gets a pair of zip tie slots at the back, and the band's groove runs
across the underside between them, so the base sits flat on its ties. Two clamp tabs at
each end, 22 mm out past the base, hold it to the desk: a flat tab at the
back corner for the base lying flat, and an upright flush with the front
face, the full height of the base, that lies on the desk when the base
stands on its front face. The tabs sit at opposite ends of the base so
neither stands in the other's clamp air, and a clamp jaw lands on a clear
22 x 30 mm face in either pose.

The horn is the MG90S four-arm horn, on one 2.05 mm plate: two long arms
of 16.2 and 18.2 mm (six and seven holes) and two short ones of 8.1 mm at
right angles to them, with a 6.65 mm hub that stands 0.3 mm above the plate
and a 2.2 mm collar under it. All three mounts share one seat on the horn.
It is keyed to all four arms, so a mount goes on one way only, the longer
arm toward +X. The key reaches 1.5 mm into the plate, which keeps the skirt around it
clear of the boss under the horn; the skirt is a full circle that encloses
the long arms and stays inside the tag plate's square. The mount's underside
sits on the plate's top face across all four arms, which makes that face the
flatness reference. The hub rises into a clearance recess and the M2 center
screw's head into a counterbore above it, neither touched. The mount's top,
7 mm over the plate, is a flat face printed on the bed at the height of the
reference pad's top, and a tag cap seats on each. Two
optional M1.4 screws through the long
arms' third holes, 8.8 mm out on the longer arm and 8.5 on the shorter,
opposite each other so the clamp balances,
retain a mount on the horn; they never locate it, and they stay because
the hanging load mount pries at a press fit 1.5 mm deep. The stall mount
cuts them at tap size instead, so they thread in and pin it to the horn
past the key's 0.25 mm of play. Out there their
counterbores leave a full wall to the hub's recess.

The stall mount holds the horn still for the locked sitting. It is the
camera mount's seat under one solid arm, 8 mm deep, that tapers from the
head's full width to an ear 70 mm out, and it takes no cap. An M3 x 25
button head screw, its head on the ear's top face, cuts its own thread in
2.8 mm holes through the ear and the base, 0.2 under its major diameter
like the board's M2 pilots, so nothing around it has play, passes a
washer between the two, and draws up an M3 nut held in a tight
hex pocket in the base's underside. The pocket closes under a 45 degree
roof, so it prints without a bridge, and the nut seats against that roof.
The servo is commanded to the angle that puts the screw over the hole,
within one spline tooth of mid travel, and that angle is the lock
position. The lever is what makes the lock stiff: 0.1 mm of play at the
screw is 0.08 degrees at 70 mm, against 0.23 at the 25 mm of an ear
beside the cap. The arm reaches past the reference pad's near edge, so it
cannot sweep the travel, and the camera sittings use the camera mount.

The load mount is two prints. The mount is the camera mount's hub, the
same keyed seat, retaining screws and plate, with a flat beam whose top is
the plate's. The beam leaves the plate at its full width and tapers to an
18 mm core under the block's center, with no neck; a shallow groove beside
the core takes the cap's corner grips where they hang down the plate's
side, and the cap's notch passes the core. It prints top down like the
camera mount and its cap carries the hub tag at the reference tag's height: both tags stay equidistant from the
lens under load too. The block is a 2 x 2 block of coin cups centered
55 mm from the axis, sitting on the beam: four stacks of 12 US quarters,
272 g, dropped in by pairs so the load balances across the arm. The inner
pair, the outer pair and all four make a load ladder of 55, 92 and
147 mN m with the arm level, 28 or 46 mN m for one stack. The cups open
away from the base, so the block prints floor down with nothing bridging,
and a lid with four plugs closes them under one M2 screw into the column
where the four cups meet. A flange on the block's inner end lies on the
beam past the cap's edge, and two M2.5 x 8 screws go down through both
into nuts pressed into hex pockets in the beam's underside. Every screw
head faces the camera; the beam's underside, 3.5 mm over the base top,
carries nothing proud, and the screw tips end flush with it. The base
stands on its front face at the desk edge and the arm hangs down at mid
travel, the coins lying on the cup walls, closed in if the block ever
comes off.

Each tag rides in a cap, so a tag is made once, kept flat and covered at
its edges, and moved between the camera mount, the load mount and the
pad, or onto any
later rig that grows the same plate. The interface is the plate: a 40.4 mm
square with a flat top and at least 3 mm of straight side under it. The
cap base is a 1.2 mm plate of that square, printed seat down, with a
one-layer pocket on top that the paper is glued into. The cap top is a
frame whose lip covers the paper's quiet border and whose skirt centers
the cap base and grips the plate's side below it, notched for the load
mount's beam. Two crush ribs on each side of the skirt do the gripping:
half-round, 0.3 mm proud of the fit, they press into the plate wherever
the printed walls land, which a plain wall fit cannot promise. They stop
at the plate's top face: pressed into its edges, the 1.2 mm cap base
bows and the paper with it, so it is trapped between the lip and the
plate instead. Both print without a bridge, which a single part with a
floor and a skirt could not. The pair seats on the plate's top face, the
flatness reference, and puts the paper's face 1.0 mm above it, the same on
every plate, so the two tags stay equidistant from the lens. A cap seats
within about 0.3 degrees of square; that offset holds for a session and
comes out with the zero, while the tilt that the 1 degree acceptance
guards is set by the seat alone. The lip stands 0.6 mm above the cap base.

Nothing of the base rises inside the keep-out circle, which is the circle
the camera mount's cap sweeps plus the tag's quiet
border. The board pocket sits back where the loaded arm clears it by 2 mm
at 10 degrees past each end of a 180 degree travel, which also sets the
reference pad's place; a servo with more travel needs a look.

Frame: X east, Y north (the back), Z up, the horn axis on Z and Z = 0 the
base's underside. At mid travel the stall mount's ear points +X over its
hole and the load mount points -Y, toward the front face. The base prints
on its underside, the three mounts, the lid and the cap top print top
down, so
each cap seat comes off the bed flat, the block and the cap base print
floor down, and no part needs support.

A fit test print goes first: a thin plate with the mounts' key pocket at
four fits, 0.05 to 0.35 mm per side, each labeled, and a 10 mm
section of the servo pocket with its ear ledge and lead slot. The real horn
and servo pick the fit, which becomes the key and pocket clearance of every
part after it.

Servo and horn dimensions come from a STEP model of the Tower Pro MG90S
(GrabCAD), the horn's shorter long arm cut back one hole pitch to match the
horn at hand. The heights that set where the horn lands are worth a caliper
check on the servo at hand and go in as command line overrides before the
print (README.md lists them).

    uv run --group cad python -m rigs.servorig [--head-h 1.6 ...]
    writes rigs/servorig/build/
"""
