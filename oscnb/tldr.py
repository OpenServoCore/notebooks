"""The constants table of a stage README's TL;DR, filled from the results files.

A stage that has a TL;DR keeps a spec next to its README, `tldr.toml`, with
the hand-written parts of each row: the label, which result and key, the
display unit and figures, what the bounds are, the confidence word. Value,
bounds and unit come from the results files every time, so the table cannot
drift from them. The README carries the table between two markers, and this
module rewrites only what sits between them.

    uv run python -m oscnb.tldr           # rewrite every stage's table
    uv run python -m oscnb.tldr --check   # exit 1 if a README is stale

The spec, one `[[constant]]` table per row:

    pair = "dev-v006-2A-D"      # optional, the default results/<pair>.json
    [[constant]]
    label = "DMM log lag behind the host clock"
    experiment = "dmm"
    key = "lag_s"               # dotted path into the results file
    pair = "..."                # optional, overrides the stage default
    unit = "ms"                 # optional, the results unit by default
    scale = 1e3                 # required when unit differs from the results
    subtract = 1.0              # optional, taken off before scaling
    sig = 2                     # significant figures of the value, or
    decimals = 1                # a fixed number of decimals
    signed = true               # optional, a + on positive numbers
    bounds = "spread, ..."      # what lo to hi is, required when they exist
    confidence = "measured"
    notebook = "dmm/dmm.ipynb"  # optional, <experiment>/<experiment>.ipynb
    class = true                # optional, key is a {pct, fixed} class
"""
import math
import sys
import tomllib

from oscnb import results

BEGIN = "<!-- tldr:constants:begin -->"
END = "<!-- tldr:constants:end -->"
STAMP = "<!-- generated by `uv run python -m oscnb.tldr` from tldr.toml and the results files, edit those instead -->"
HEADER = ("| Constant | Value | Bounds | Unit | Confidence | Notebook |\n"
          "|---|---|---|---|---|---|")


def stage_dir(stage):
    return results.ROOT / "stages" / stage


def stages():
    """The stages that have a TL;DR spec. A stage without one is skipped."""
    return sorted(p.parent.name for p in (results.ROOT / "stages").glob("*/tldr.toml"))


def spec(stage):
    return tomllib.loads((stage_dir(stage) / "tldr.toml").read_text())


def lookup(doc, key):
    node = doc
    for part in key.split("."):
        if not isinstance(node, dict) or part not in node:
            raise KeyError(f"no {key!r} in the results")
        node = node[part]
    return node


def decimals(row, value):
    if "decimals" in row:
        return int(row["decimals"])
    sig = int(row["sig"])
    if value == 0:
        raise ValueError(f"{row['label']}: a zero value needs decimals, not sig")
    return max(0, sig - 1 - math.floor(math.log10(abs(value))))


def number(x, places, signed=False):
    s = f"{x:+.{places}f}" if signed else f"{x:.{places}f}"
    if float(s) == 0:
        s = s.lstrip("+-")
    return s


def short(x):
    """A manual's class figure, as plainly as it reads in the manual."""
    return f"{round(x, 9):g}"


def cells(row, doc):
    label = row["label"]
    q = lookup(doc, row["key"])
    if row.get("class"):
        unit = row.get("unit", q["fixed"]["unit"])
        scale = float(row.get("scale", 1.0))
        if unit != q["fixed"]["unit"] and "scale" not in row:
            raise ValueError(f"{label}: unit {unit!r} differs from {q['fixed']['unit']!r} with no scale")
        value = f"{short(q['pct']['value'])} % of reading + {short(q['fixed']['value'] * scale)}"
        if "bounds" not in row:
            raise ValueError(f"{label}: a class row says where the class comes from in bounds")
        return value, row["bounds"], unit
    unit = row.get("unit", q["unit"])
    if unit != q["unit"] and "scale" not in row:
        raise ValueError(f"{label}: unit {unit!r} differs from the result's {q['unit']!r} with no scale")
    scale, sub, signed = float(row.get("scale", 1.0)), float(row.get("subtract", 0.0)), bool(row.get("signed"))
    v = (q["value"] - sub) * scale
    places = decimals(row, v)
    value = number(v, places, signed)
    if q["lo"] is None and q["hi"] is None:
        if "bounds" in row:
            raise ValueError(f"{label}: the result has no bounds, so the spec gives none")
        return value, "-", unit or "-"
    if "bounds" not in row:
        raise ValueError(f"{label}: the result has bounds, the spec has to say what they are")
    lo = "-" if q["lo"] is None else number((q["lo"] - sub) * scale, places, signed)
    hi = "-" if q["hi"] is None else number((q["hi"] - sub) * scale, places, signed)
    return value, f"{lo} to {hi}, {row['bounds']}", unit or "-"


def table(stage):
    s = spec(stage)
    lines = [STAMP, HEADER]
    for row in s.get("constant", []):
        doc = results.read(stage, row["experiment"], row.get("pair", s.get("pair")))
        value, bounds, unit = cells(row, doc)
        nb = row.get("notebook", f"{row['experiment']}/{row['experiment']}.ipynb")
        out = [row["label"], value, bounds, unit, row["confidence"], f"[{row['experiment']}]({nb})"]
        if any("|" in c or "\n" in c for c in out):
            raise ValueError(f"{row['label']}: a cell holds a | or a line break")
        lines.append("| " + " | ".join(out) + " |")
    return "\n".join(lines)


def render(stage):
    """The stage README with its constants block regenerated."""
    text = (stage_dir(stage) / "README.md").read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError(f"stages/{stage}/README.md needs one {BEGIN} ... {END} block")
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    return f"{head}{BEGIN}\n{table(stage)}\n{END}{tail}"


def main(argv):
    check = "--check" in argv
    stale = []
    for stage in stages():
        readme = stage_dir(stage) / "README.md"
        new = render(stage)
        if new != readme.read_text():
            stale.append(stage)
            if not check:
                readme.write_text(new)
    for stage in stale:
        print(f"stages/{stage}/README.md {'is stale' if check else 'rewritten'}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
